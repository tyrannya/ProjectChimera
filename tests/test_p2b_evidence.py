# --------------------------------------------------------------------------- #
# F. coverage cannot be opted out of by the thing being covered
#
# `evidence_class` lives in the artifact's own JSON, and the freeze tool reads
# it to decide what to hash. That is the right default — a new aggregator has to
# opt *into* being excluded rather than remember to opt out — but it also means
# the file decides whether it is covered. A cell that flipped itself to
# "derived" would be dropped by the next freeze, and every test above would
# still pass: the manifest would cover only declared-primary directories, no
# covered directory would be derived, and the cell would simply have vanished
# from the evidence.
#
# So what is expected to be primary is declared **here**, out of reach of
# anything under `artifacts/`, and derived from the checkpoint definitions in
# `nn.information_sets` rather than from a directory listing. A checkpoint that
# gains an arm gains a required cell, and no artifact can edit this list.
# --------------------------------------------------------------------------- #
CELL_MANIFEST = {
    "P2b": "btc_p2b_SHA256SUMS.txt",
    "P2c": "btc_p2c_SHA256SUMS.txt",
    "P3": "btc_p3_SHA256SUMS.txt",
    "P4": "btc_p4_stage1_SHA256SUMS.txt",
    "P5": "btc_p5_SHA256SUMS.txt",
}
ABLATION_MANIFEST = "btc_p2b_ablation_SHA256SUMS.txt"

#: Checkpoints this repository declares but has produced **no evidence for**,
#: and the manifest each one will be frozen under when it does.
#:
#: Declared rather than inferred, and for the same reason the rest of this
#: section exists. A checkpoint with no cells is invisible to a coverage check
#: built from directory listings: nothing is missing because nothing is
#: expected. Naming it here means the repository has to say *why* a declared
#: checkpoint has no evidence, and
#: `test_an_unrun_checkpoint_has_no_evidence_directories` fails the moment one
#: appears without being moved into `CELL_MANIFEST`.
UNRUN_CHECKPOINTS: dict[str, str] = {}


def expected_primary() -> dict[str, str]:
    """Directory name -> the manifest that must cover it, in full."""
    expected: dict[str, str] = {}
    for checkpoint, manifest in CELL_MANIFEST.items():
        for arm in CHECKPOINTS[checkpoint].arms:
            for model in SIMPLE_MODEL_NAMES:
                expected[f"btc_{checkpoint.lower()}_{arm}_{model}"] = manifest
    for arm in ablation_set_names():
        expected[f"btc_p2b_{arm}_xgboost"] = ABLATION_MANIFEST
    expected["btc_p2b_repro_ohlcv14_plus_smc_v1_xgboost"] = ABLATION_MANIFEST
    return expected


def coverage(entries_by_manifest: dict[str, list[str]]) -> dict[str, set[str]]:
    """Directory name -> the manifests covering any file in it."""
    covered: dict[str, set[str]] = {}
    for manifest, names in entries_by_manifest.items():
        for name in names:
            covered.setdefault(Path(name).parent.name, set()).add(manifest)
    return covered


def coverage_problems(
    expected: dict[str, str], entries_by_manifest: dict[str, list[str]]
) -> list[str]:
    """Every expected primary directory not covered exactly once, by the right manifest."""
    covered = coverage(entries_by_manifest)
    problems: list[str] = []
    for directory, manifest in sorted(expected.items()):
        found = covered.get(directory, set())
        if not found:
            problems.append(
                f"{directory} is expected primary evidence and no manifest covers it"
            )
        elif len(found) > 1:
            problems.append(f"{directory} is covered by {sorted(found)}; exactly one may")
        elif found != {manifest}:
            problems.append(f"{directory} is covered by {found.pop()}, expected {manifest}")
    return problems


def _committed_entries() -> dict[str, list[str]]:
    return {
        manifest: [
            name for _, name in freeze_evidence.manifest_entries(ROOT / "artifacts" / manifest)
        ]
        for manifest in MANIFESTS
    }


def test_every_declared_checkpoint_is_frozen_or_declared_unrun():
    """No checkpoint may be neither. That is how one would escape coverage."""
    assert set(CHECKPOINTS) == set(CELL_MANIFEST) | set(UNRUN_CHECKPOINTS)
    assert not set(CELL_MANIFEST) & set(UNRUN_CHECKPOINTS)


@pytest.mark.parametrize("checkpoint", sorted(UNRUN_CHECKPOINTS))
def test_an_unrun_checkpoint_has_no_evidence_directories(checkpoint):
    """A checkpoint declared unrun must have produced nothing at all.

    The moment a cell appears, this fails — and the fix is to move the
    checkpoint into `CELL_MANIFEST`, which immediately demands all nine cells,
    their manifest, and every file inside each directory. Evidence cannot
    arrive quietly.
    """
    prefix = f"btc_{checkpoint.lower()}_"
    strays = sorted(p.name for p in BENCHMARK.glob(f"{prefix}*"))
    assert strays == [], (
        f"{checkpoint} is declared unrun but {strays} exist. Move it into "
        "CELL_MANIFEST and freeze its cells rather than leaving them uncovered."
    )
    assert not (ROOT / "artifacts" / UNRUN_CHECKPOINTS[checkpoint]).exists()


def test_every_expected_primary_directory_is_covered_exactly_once():
    assert coverage_problems(expected_primary(), _committed_entries()) == []


def test_every_file_in_an_expected_primary_directory_is_covered():
    """Coverage of a directory is not coverage of the cell.

    A manifest naming `p2b.json` and not `outer_predictions.parquet` would pass
    the check above while leaving the per-sample evidence unpinned.
    """
    entries = _committed_entries()
    covered = {name for names in entries.values() for name in names}
    for directory in expected_primary():
        on_disk = {
            f"artifacts/benchmark/{directory}/{p.name}"
            for p in (BENCHMARK / directory).iterdir()
            if p.suffix in freeze_evidence.EVIDENCE_SUFFIXES
        }
        assert on_disk, f"{directory} holds no evidence files"
        assert on_disk <= covered, f"{directory}: uncovered {sorted(on_disk - covered)}"


def test_no_expected_primary_directory_declares_itself_derived():
    """The opt-out this section exists to close, stated as its own failure.

    Without this, a cell that flipped to "derived" would fail
    `test_no_manifest_covers_derived_evidence` instead — which reads as "remove
    it from the manifest" when the correct answer is "a cell is not derived".
    """
    for directory in expected_primary():
        declared = freeze_evidence.evidence_class_of(BENCHMARK / directory)
        assert declared == PRIMARY, f"{directory} declares {declared!r}"


# --- and falsified ------------------------------------------------------------
#
# Against a synthetic manifest set rather than the committed one, deliberately:
# a check on coverage must be falsifiable without the evidence it guards being
# in place, or it cannot be trusted at the moment the coverage is being cut.
def _synthetic_entries(expected: dict[str, str]) -> dict[str, list[str]]:
    """Exactly the coverage `expected` asks for: two files per directory."""
    entries: dict[str, list[str]] = {manifest: [] for manifest in set(expected.values())}
    for directory, manifest in expected.items():
        entries[manifest] += [
            f"artifacts/benchmark/{directory}/p2b.json",
            f"artifacts/benchmark/{directory}/outer_predictions.parquet",
        ]
    return entries


def test_complete_coverage_reports_nothing():
    """The control. A checker that always complained would pass the three below."""
    expected = expected_primary()
    assert coverage_problems(expected, _synthetic_entries(expected)) == []


def test_a_cell_that_removed_itself_from_coverage_is_reported():
    """The attack this section exists for: a cell relabels itself `derived`, so
    the next freeze drops it, and the manifests stay internally consistent."""
    expected = expected_primary()
    entries = _synthetic_entries(expected)
    victim = "btc_p2c_chart_structure_v1_xgboost"
    entries[CELL_MANIFEST["P2c"]] = [
        n for n in entries[CELL_MANIFEST["P2c"]] if f"/{victim}/" not in n
    ]
    assert coverage_problems(expected, entries) == [
        f"{victim} is expected primary evidence and no manifest covers it"
    ]


def test_a_cell_covered_by_two_manifests_is_reported():
    expected = expected_primary()
    entries = _synthetic_entries(expected)
    entries[ABLATION_MANIFEST] += ["artifacts/benchmark/btc_p2b_ohlcv14_xgboost/p2b.json"]
    both = sorted([ABLATION_MANIFEST, CELL_MANIFEST["P2b"]])
    assert coverage_problems(expected, entries) == [
        f"btc_p2b_ohlcv14_xgboost is covered by {both}; exactly one may"
    ]


def test_a_cell_covered_by_the_wrong_manifest_is_reported():
    expected = expected_primary()
    entries = _synthetic_entries(expected)
    moved = [n for n in entries[CELL_MANIFEST["P2b"]] if "/btc_p2b_smc_v1_lightgbm/" in n]
    entries[CELL_MANIFEST["P2b"]] = [
        n for n in entries[CELL_MANIFEST["P2b"]] if n not in moved
    ]
    entries[ABLATION_MANIFEST] += moved
    assert coverage_problems(expected, entries) == [
        f"btc_p2b_smc_v1_lightgbm is covered by {ABLATION_MANIFEST}, "
        f"expected {CELL_MANIFEST['P2b']}"
    ]


