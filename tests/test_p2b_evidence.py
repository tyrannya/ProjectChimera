def test_the_four_outer_periods_are_the_ones_the_write_up_describes():
    """`artifacts/README.md` and the roadmap both describe these four blocks as
    positive-return, low-directionality stretches. If that stopped being true the
    prose would be wrong and nothing else would say so."""
    payload = json.loads((BENCHMARK / "btc_p2b_regimes" / "p2b_regimes.json").read_text())
    assert [p["fold"] for p in payload["periods"]] == [0, 1, 2, 3]
    ratios = []
    for period in payload["periods"]:
        market = period["market"]
        assert market["total_return"] > 0, f"fold {period['fold']} was not positive-return"
        ratios.append(round(market["directionality"], 4))
    # The band the roadmap quotes, taken from the artifact rather than from
    # memory. It said 0.012-0.055 until this test was written, which is fold 0's
    # ratio mistaken for the minimum — fold 2 is 0.0030, an order of magnitude
    # lower and the choppiest of the four. The artifact's own `observations`
    # said so all along; the prose had simply never been checked against it.
    assert min(ratios) == 0.0030 and max(ratios) == 0.0552, ratios
    assert all(r < 0.06 for r in ratios), "these are low-directionality blocks"


