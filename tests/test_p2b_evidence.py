# --------------------------------------------------------------------------- #
# E. the derived reports nothing was checking
#
# The two comparisons are pinned by their fold counts, verdicts and integrity
# counters. The ablation table and the regime description had neither a hash nor
# an assertion: they are derived, so freezing them is wrong, and nothing else
# looked at them at all. Both carry research-relevant numbers — the six family
# contributions, the per-fold deltas behind the regime reading — and both are
# regenerated by a tool that could start producing different ones without a
# single test noticing.
#
# They are checked the way a derived report should be: **recomputed from the
# primary evidence behind them**. Each helper below is a pure function of
# (payload, cells) so the real evidence exercises it and a tampered payload can
# falsify it without copying the committed artifacts.
# --------------------------------------------------------------------------- #
def _fold_net_returns(cell: str, model: str) -> dict[int, float]:
    """One cell's outer net return per fold, read from the cell itself."""
    payload = json.loads((BENCHMARK / cell / "p2b.json").read_text())
    return {
        int(record["fold"]): record["outer_validation"][model]["trading"]["net_return"]
        for record in payload["folds"]
    }


def ablation_mismatches(payload: dict, net_returns) -> list[str]:
    """Every ablation number that is not what the cells behind it imply.

    ``net_returns(cell_directory)`` returns ``{fold: net_return}``. The delta
    definition is the artifact's own: full minus ablated, per fold, on identical
    rows.
    """
    problems: list[str] = []
    model = payload["model"]
    full = net_returns(f"btc_p2b_{payload['reference_arm']}_{model}")
    for family, block in payload["families"].items():
        ablated = net_returns(f"btc_p2b_{block['arm']}_{model}")
        for record in block["per_fold"]:
            fold = int(record["fold"])
            for key, expected in (
                ("full_net_return", full[fold]),
                ("ablated_net_return", ablated[fold]),
                ("net_return", round(full[fold] - ablated[fold], 6)),
            ):
                if record[key] != round(expected, 6):
                    problems.append(
                        f"{family} fold {fold} {key}: report says {record[key]}, the "
                        f"cells give {round(expected, 6)}"
                    )
        deltas = [record["net_return"] for record in block["per_fold"]]
        mean = round(sum(deltas) / len(deltas), 6)
        if block["aggregate"]["net_return"]["mean"] != mean:
            problems.append(
                f"{family} mean delta: report says "
                f"{block['aggregate']['net_return']['mean']}, its own folds give {mean}"
            )
        signs = block["sign_consistency"]["net_return"]
        if signs["positive"] != sum(1 for d in deltas if d > 0):
            problems.append(f"{family} positive-fold count disagrees with its own deltas")
        if signs["negative"] != sum(1 for d in deltas if d < 0):
            problems.append(f"{family} negative-fold count disagrees with its own deltas")
    return problems


def regime_delta_mismatches(payload: dict, net_returns) -> list[str]:
    """Every per-fold delta in the regime description the cells do not support."""
    problems: list[str] = []
    for model, by_fold in payload["deltas_by_model"].items():
        control = net_returns(f"btc_p2b_ohlcv14_{model}")
        for fold, arms in by_fold.items():
            for arm, delta in arms.items():
                theirs = net_returns(f"btc_p2b_{arm}_{model}")
                expected = round(theirs[int(fold)] - control[int(fold)], 6)
                if delta != expected:
                    problems.append(
                        f"{model} fold {fold} {arm}: report says {delta}, the cells "
                        f"give {expected}"
                    )
    return problems


